// Writes src/styles/font-fallbacks.css: system fonts resized to the exact proportions of the
// web fonts, so text does not jump when the web fonts finish loading (no layout shift).
// Run with: npm run font-fallbacks   (only needed if the fonts change)
import { createFontStack } from '@capsizecss/core';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import inter from '@capsizecss/metrics/inter';
import sourceSerif4 from '@capsizecss/metrics/sourceSerif4';
import jetBrainsMono from '@capsizecss/metrics/jetBrainsMono';
import plexArabic from '@capsizecss/metrics/iBMPlexSansArabic';
import naskhArabic from '@capsizecss/metrics/notoNaskhArabic';
import arial from '@capsizecss/metrics/arial';
import georgia from '@capsizecss/metrics/georgia';
import courierNew from '@capsizecss/metrics/courierNew';
import segoeUI from '@capsizecss/metrics/segoeUI';
import timesNewRoman from '@capsizecss/metrics/timesNewRoman';

// [web font, system font it falls back to, name used in CSS]
const pairs = [
  [inter, arial, 'Inter Fallback'],
  [sourceSerif4, georgia, 'Source Serif 4 Fallback'],
  [jetBrainsMono, courierNew, 'JetBrains Mono Fallback'],
  [plexArabic, segoeUI, 'IBM Plex Sans Arabic Fallback'],
  [naskhArabic, timesNewRoman, 'Noto Naskh Arabic Fallback'],
];

let css = '/* Generated by scripts/make-font-fallbacks.mjs — do not edit by hand. */\n';
for (const [font, fallback, name] of pairs) {
  const { fontFaces } = createFontStack([font, fallback], {
    fontFaceProperties: { fontDisplay: 'swap' },
  });
  // Capsize names the face "<Font> Fallback: <System>"; use a stable, simple name instead.
  css += fontFaces.replace(/font-family: "[^"]+";/, `font-family: "${name}";`) + '\n';
}

const out = fileURLToPath(new URL('../src/styles/font-fallbacks.css', import.meta.url));
writeFileSync(out, css);
console.log(`Wrote ${out}`);
